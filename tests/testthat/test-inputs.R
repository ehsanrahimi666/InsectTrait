test_that("species folders are read with species names", {
  d <- file.path(tempdir(), "it_species")
  unlink(d, recursive = TRUE)
  ex <- in_example_photos()
  dir.create(file.path(d, "Harmonia_axyridis"), recursive = TRUE)
  dir.create(file.path(d, "Aglais io"), recursive = TRUE)
  file.copy(ex$photo[1], file.path(d, "Harmonia_axyridis", "a 1.jpg"))
  file.copy(ex$photo[4], file.path(d, "Aglais io", "a 1.jpg"))
  file.copy(ex$photo[2], file.path(d, "loose.jpg"))
  f <- in_read_folder(d)
  expect_equal(nrow(f), 3)
  expect_setequal(f$species, c("Harmonia axyridis", "Aglais io", NA))
  expect_false(anyDuplicated(f$photo_id) > 0)
  expect_true(all(file.exists(f$path)))
  expect_true(all(grepl("^[A-Za-z0-9._-]+$", f$photo_id)))
  expect_true(all(is.na(in_read_folder(d, species_from_folder = FALSE)$species)))
  expect_equal(nrow(in_read_folder(d, recursive = FALSE)), 1)
  it <- InsectTrait:::.in_items(d)
  expect_equal(sort(it$species, na.last = TRUE), sort(f$species, na.last = TRUE))
  expect_error(in_read_folder(file.path(d, "nope")), "not found")
})

test_that("iNaturalist records are parsed into one row per photo", {
  js <- jsonlite::read_json(test_path("fixtures", "inat_observations.json"), simplifyVector = FALSE)
  p <- InsectTrait:::.in_parse_inat(js$results)
  expect_equal(nrow(p), 3)
  expect_true(all(grepl("/original\\.", p$url)))
  expect_equal(unique(p$species), "Harmonia axyridis")
  expect_true(all(p$license %in% c("cc0", "cc-by")))
  p4 <- InsectTrait:::.in_parse_inat(js$results, max_per_observation = 4)
  expect_equal(nrow(p4), 6)
  expect_equal(nrow(InsectTrait:::.in_parse_inat(js$results, license = "cc0")), 2)
  expect_equal(nrow(InsectTrait:::.in_parse_inat(list())), 0)
  p$occurrenceKey <- NA
  a <- in_attribution(p)
  expect_true(all(grepl("iNaturalist, https://www.inaturalist.org/observations/", a)))
})

test_that("live iNaturalist and GBIF lookups work for insects only", {
  skip_on_cran()
  skip_on_ci()
  skip_if_offline("api.inaturalist.org")
  ip <- in_inat_photos("Aglais io", n = 2)
  expect_lte(nrow(ip), 2)
  expect_true(all(ip$order == "Lepidoptera"))
  expect_error(in_inat_photos("Parus major", n = 1), "not an insect")
  tx <- in_taxonomy(c("Apis mellifera", "Vanessa atalanta"))
  expect_equal(tx$order, c("Hymenoptera", "Lepidoptera"))
  expect_warning(in_taxonomy("Parus major"), "insect")
})
